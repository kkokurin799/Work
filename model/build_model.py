def recalc_values(path):
    """Пересчитывает книгу в LibreOffice и возвращает значения всех формул."""
    soffice = shutil.which("soffice")
    if not soffice:
        return None
    from openpyxl import load_workbook

    with tempfile.TemporaryDirectory() as tmp:
        profile = os.path.join(tmp, "profile", "user")
        os.makedirs(profile)
        with open(os.path.join(profile, "registrymodifications.xcu"), "w", encoding="utf-8") as fh:
            fh.write(
                '<?xml version="1.0" encoding="UTF-8"?>\n'
                '<oor:items xmlns:oor="http://openoffice.org/2001/registry" '
                'xmlns:xs="http://www.w3.org/2001/XMLSchema" '
                'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">\n'
                '<item oor:path="/org.openoffice.Office.Calc/Formula/Load">'
                '<prop oor:name="OOXMLRecalcMode" oor:op="fuse"><value>0</value></prop></item>\n'
                '</oor:items>\n'
            )
        subprocess.run([soffice, f"-env:UserInstallation=file://{os.path.join(tmp, 'profile')}",
                        "--headless", "--convert-to", "xlsx", "--outdir", tmp, path],
                       check=True, capture_output=True)
        calc = os.path.join(tmp, os.path.basename(path))
        vals = load_workbook(calc, data_only=True)
        forms = load_workbook(path)
        out = {}
        for ws in forms:
            for row in ws.iter_rows():
                for c in row:
                    if isinstance(c.value, str) and c.value.startswith("="):
                        out[(ws.title, c.coordinate)] = vals[ws.title][c.coordinate].value
        return out


if __name__ == "__main__":
    build(OUT)
    values = recalc_values(OUT)
    if values:
        build(OUT, values)
    print("saved", OUT, "with cached values" if values else "without cached values")
